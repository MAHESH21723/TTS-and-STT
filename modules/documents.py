"""Plain-text and PDF exports of a conversion."""
from __future__ import annotations

import sqlite3

from fpdf import FPDF
from fpdf.enums import XPos, YPos


def conversion_text(row: sqlite3.Row) -> str:
    """The human text of a row: the input for TTS, the transcription for STT."""
    return row["input_data"] if row["operation_type"] == "TTS" else row["output_data"]


def build_pdf(row: sqlite3.Row, language_name: str) -> bytes:
    """Render a one-document PDF report.

    The built-in PDF fonts only cover Latin-1, so other scripts (e.g. Tamil)
    are replaced with '?'. Use the TXT export for the full text.
    """
    is_tts = row["operation_type"] == "TTS"
    pdf = FPDF()
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(0, 15, "Speech Studio Report", new_x=XPos.LMARGIN, new_y=YPos.NEXT, align="C")
    pdf.ln(4)

    meta = [
        ("Conversion ID:", str(row["id"])),
        ("Operation:", "Text-to-Speech" if is_tts else "Speech-to-Text"),
        ("Language:", language_name),
        ("Date:", str(row["created_at"])),
    ]
    for label, value in meta:
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(35, 7, label)
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(0, 7, value.encode("latin-1", "replace").decode("latin-1"),
                 new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(6)

    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "Input text" if is_tts else "Transcription",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font("Helvetica", "", 11)
    body = conversion_text(row).encode("latin-1", "replace").decode("latin-1")
    pdf.multi_cell(0, 7, body, wrapmode="CHAR")

    pdf.ln(12)
    pdf.set_font("Helvetica", "I", 9)
    pdf.cell(0, 10, "Generated by Speech Studio", align="C")
    return bytes(pdf.output())
